// Builds index.html and case-studies/*.html from the markdown files in content/.
// Run with: npm run build
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import matter from 'gray-matter';
import { marked } from 'marked';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = (rel) => matter(fs.readFileSync(path.join(root, rel), 'utf8'));

const esc = (s = '') => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const block = (md) => marked.parse(md.trim());
const inline = (md) => marked.parseInline(md.trim());

// Split a markdown body into an intro and "## Heading" sections.
function sections(body) {
  const parts = body.split(/^## /m);
  const intro = parts.shift().trim();
  const items = parts.map((p) => {
    const i = p.indexOf('\n');
    return { title: p.slice(0, i).trim(), md: p.slice(i + 1).trim() };
  });
  return { intro, items };
}

// Pull a "Case study: [Name](slug)" line out of a section; slugs map to case study pages.
function takeCaseLine(md, prefix = '') {
  const m = md.match(/^(Case stud(?:y|ies)):\s*(.+)$/mi);
  if (!m) return { md, row: '' };
  const links = [...m[2].matchAll(/\[([^\]]+)\]\(([^)]+)\)/g)]
    .map(([, name, slug]) => `<a href="${prefix}case-studies/${slug}.html" class="link-nav text-white">${esc(name)}</a>`);
  const label = m[1].toLowerCase().endsWith('ies') ? 'CASE STUDIES' : 'CASE STUDY';
  return { md: md.replace(m[0], '').trim(), row: { label, links: links.join(' &middot; ') } };
}

